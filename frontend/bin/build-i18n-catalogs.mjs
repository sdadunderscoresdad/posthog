// Generates frontend/src/lib/i18n/catalogLoaders.ts from the catalogs on disk, and reports every way
// the catalogs disagree with the locale registry. Pass --check to verify without writing.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const i18nDir = path.resolve(__dirname, '../src/lib/i18n')
const localesDir = path.join(i18nDir, 'locales')
const outputFile = path.join(i18nDir, 'catalogLoaders.ts')
const OUTPUT_BANNER = '// Generated by frontend/bin/build-i18n-catalogs.mjs. Do not edit by hand.'

function findInitializer(fileName, exportName) {
    const source = ts.createSourceFile(fileName, fs.readFileSync(fileName, 'utf8'), ts.ScriptTarget.Latest, true)
    let found
    const visit = (node) => {
        if (
            ts.isVariableDeclaration(node) &&
            ts.isIdentifier(node.name) &&
            node.name.text === exportName &&
            node.initializer
        ) {
            found = node.initializer
        }
        ts.forEachChild(node, visit)
    }
    visit(source)
    return found
}

/** Look through `as const`, `satisfies T`, and parentheses to reach the value itself. */
function peelWrappers(node) {
    let current = node
    while (
        ts.isAsExpression(current) ||
        ts.isSatisfiesExpression(current) ||
        ts.isParenthesizedExpression(current) ||
        ts.isTypeAssertionExpression(current)
    ) {
        current = current.expression
    }
    return current
}

/** The declared names of an exported list, written either as an object literal or as an array. */
function readExportedNames(fileName, exportName) {
    const initializer = peelWrappers(findInitializer(fileName, exportName))
    if (!initializer) {
        throw new Error(`Could not find ${exportName} in ${fileName}`)
    }
    if (ts.isArrayLiteralExpression(initializer)) {
        return initializer.elements.map((element) => {
            if (!ts.isStringLiteral(element)) {
                throw new Error(`${exportName} in ${fileName} must list plain string names`)
            }
            return element.text
        })
    }
    if (!ts.isObjectLiteralExpression(initializer)) {
        throw new Error(`Could not read ${exportName} from ${fileName}`)
    }
    return initializer.properties.map((property) => {
        if (!ts.isPropertyAssignment(property)) {
            throw new Error(`${exportName} in ${fileName} must contain plain properties`)
        }
        const name = property.name
        if (!ts.isIdentifier(name) && !ts.isStringLiteral(name)) {
            throw new Error(`${exportName} in ${fileName} has a computed property name`)
        }
        return name.text
    })
}

function readStringConstant(fileName, exportName) {
    const initializer = peelWrappers(findInitializer(fileName, exportName))
    if (!initializer || !ts.isStringLiteral(initializer)) {
        throw new Error(`Could not read the string exported as ${exportName} from ${fileName}`)
    }
    return initializer.text
}

/** The interpolation names a message declares, which every translation of it must repeat. */
function placeholdersOf(message) {
    return [...message.matchAll(/\{\{\s*([\w.]+)/g)].map((match) => match[1]).sort()
}

const PLURAL_SUFFIXES = ['_zero', '_one', '_two', '_few', '_many', '_other']

/**
 * The key without its plural suffix.
 *
 * Languages carry different plural categories, so the extractor writes `_one` and `_other` for
 * English but also `_few` and `_many` for Russian. Those are forms of one message, not new messages,
 * so the comparison runs on the base key.
 */
function pluralBaseOf(key) {
    for (const suffix of PLURAL_SUFFIXES) {
        if (key.endsWith(suffix)) {
            return { base: key.slice(0, -suffix.length), suffix }
        }
    }
    return { base: key, suffix: '' }
}

/** Index the source catalog by base key, so any plural category a target language needs resolves. */
function indexSourceByBase(source) {
    const byBase = new Map()
    for (const [key, message] of Object.entries(source)) {
        const { base, suffix } = pluralBaseOf(key)
        if (!byBase.has(base)) {
            byBase.set(base, new Map())
        }
        byBase.get(base).set(suffix, message)
    }
    return byBase
}

/** Catalogs nest on the key separator, so compare them as flat dotted keys. */
function flattenMessages(value, relativePath, problems, prefix = '') {
    const flat = {}
    for (const [key, child] of Object.entries(value)) {
        const fullKey = prefix ? `${prefix}.${key}` : key
        if (typeof child === 'string') {
            flat[fullKey] = child
        } else if (child !== null && typeof child === 'object' && !Array.isArray(child)) {
            Object.assign(flat, flattenMessages(child, relativePath, problems, fullKey))
        } else {
            problems.push(`${relativePath} has a value that is not a string at "${fullKey}"`)
        }
    }
    return flat
}

function readCatalog(fileName, problems) {
    const relativePath = path.relative(__dirname, fileName)
    let parsed
    try {
        parsed = JSON.parse(fs.readFileSync(fileName, 'utf8'))
    } catch (error) {
        problems.push(`${relativePath} is not valid JSON: ${error.message}`)
        return {}
    }
    if (parsed === null || typeof parsed !== 'object' || Array.isArray(parsed)) {
        problems.push(`${relativePath} must hold an object of messages`)
        return {}
    }
    return flattenMessages(parsed, relativePath, problems)
}

function collectCatalogs(localeCodes, namespaces, sourceLocale, problems) {
    const catalogs = new Map()

    for (const code of localeCodes) {
        const dir = path.join(localesDir, code)
        if (!fs.existsSync(dir)) {
            problems.push(`locales/${code}/ does not exist. Add it, with a JSON file for each name in NAMESPACES.`)
            continue
        }
        for (const file of fs.readdirSync(dir)) {
            const namespace = path.basename(file, '.json')
            if (path.extname(file) !== '.json' || !namespaces.includes(namespace)) {
                problems.push(`locales/${code}/${file} matches no name in NAMESPACES.`)
            }
        }
        for (const namespace of namespaces) {
            const fileName = path.join(dir, `${namespace}.json`)
            if (!fs.existsSync(fileName)) {
                problems.push(`locales/${code}/${namespace}.json is missing for the ${code} entry.`)
                continue
            }
            catalogs.set(`${code}/${namespace}`, readCatalog(fileName, problems))
        }
    }

    for (const entry of fs.existsSync(localesDir) ? fs.readdirSync(localesDir) : []) {
        if (!localeCodes.includes(entry)) {
            problems.push(`locales/${entry}/ has no entry in SUPPORTED_LOCALES.`)
        }
    }

    return catalogs
}

/**
 * Compare each translation against the source catalog. A translation that invents a key, drops one,
 * or loses a placeholder renders something the source never said, so all three fail the build.
 */
function checkAgainstSource(localeCodes, namespaces, sourceLocale, catalogs, problems) {
    for (const code of localeCodes) {
        if (code === sourceLocale) {
            continue
        }
        for (const namespace of namespaces) {
            const source = catalogs.get(`${sourceLocale}/${namespace}`) ?? {}
            const sourceByBase = indexSourceByBase(source)
            const translated = catalogs.get(`${code}/${namespace}`)
            if (!translated) {
                continue
            }
            for (const [key, message] of Object.entries(translated)) {
                const { base, suffix } = pluralBaseOf(key)
                const sourceVariants = sourceByBase.get(base)
                if (!sourceVariants) {
                    problems.push(
                        `locales/${code}/${namespace}.json translates "${key}", which the source catalog does not have.`
                    )
                    continue
                }
                const sourceMessage = sourceVariants.get(suffix) ?? [...sourceVariants.values()][0]
                if (message === '') {
                    // An empty value is a message the translator has not written yet, so it has no
                    // placeholders to compare against the source.
                    continue
                }
                const expected = placeholdersOf(sourceMessage).join(',')
                const actual = placeholdersOf(message).join(',')
                if (expected !== actual) {
                    problems.push(
                        `locales/${code}/${namespace}.json changes the placeholders of "${key}": expected [${expected}], found [${actual}].`
                    )
                }
            }
        }
    }
}

/** Quote a key only when it is not a bare identifier, which is the shape the formatter produces. */
function objectKey(name) {
    return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : `'${name}'`
}

function renderLoaders(localeCodes, namespaces, sourceLocale) {
    const lines = [OUTPUT_BANNER, '']
    lines.push("import type { CatalogLoader } from './catalogs'")
    lines.push("import type { TranslationNamespace } from './namespaces'")
    lines.push("import type { LocaleCode } from './supportedLocales'")
    lines.push('')
    lines.push('/**')
    lines.push(' * One import per catalog. Each entry is a static import path so that a bundler emits a')
    lines.push(' * separate chunk for it, and the loader map is what turns a language choice into a download.')
    lines.push(' *')
    lines.push(` * The source locale keeps no loader: its messages are the English text at each call site.`)
    lines.push(' */')
    lines.push(
        'export const CATALOG_LOADERS: Record<LocaleCode, Partial<Record<TranslationNamespace, CatalogLoader>>> = {'
    )
    for (const code of localeCodes) {
        const namespacesToLoad = code === sourceLocale ? [] : namespaces
        if (namespacesToLoad.length === 0) {
            lines.push(`    ${objectKey(code)}: {},`)
            continue
        }
        lines.push(`    ${objectKey(code)}: {`)
        for (const namespace of namespacesToLoad) {
            lines.push(`        ${objectKey(namespace)}: () => import('./locales/${code}/${namespace}.json'),`)
        }
        lines.push('    },')
    }
    lines.push('}')
    lines.push('')
    return lines.join('\n')
}

function main() {
    const checkOnly = process.argv.includes('--check')
    const localeCodes = readExportedNames(path.join(i18nDir, 'supportedLocales.ts'), 'SUPPORTED_LOCALES')
    const namespaces = readExportedNames(path.join(i18nDir, 'namespaces.ts'), 'NAMESPACES')
    const sourceLocale = readStringConstant(path.join(i18nDir, 'supportedLocales.ts'), 'SOURCE_LOCALE')

    const problems = []
    const catalogs = collectCatalogs(localeCodes, namespaces, sourceLocale, problems)
    checkAgainstSource(localeCodes, namespaces, sourceLocale, catalogs, problems)

    if (problems.length > 0) {
        console.error('i18n catalog check failed:')
        for (const problem of problems) {
            console.error(`  - ${problem}`)
        }
        process.exit(1)
    }

    const output = renderLoaders(localeCodes, namespaces, sourceLocale)
    const existing = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : undefined

    if (checkOnly) {
        if (existing !== output) {
            console.error('catalogLoaders.ts is out of date. Run `pnpm --filter=@posthog/frontend i18n:build`.')
            process.exit(1)
        }
        return
    }
    if (existing !== output) {
        fs.writeFileSync(outputFile, output)
        console.log(`Wrote ${path.relative(process.cwd(), outputFile)}`)
    }
}

main()
